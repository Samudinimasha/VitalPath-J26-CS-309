"""
VitalPath: 5G Security Middleware for Connected Ambulance Telemetry
Component 2: SQLite Device Trust Ingestion Client (trust_client.py)

Retrieves the latest valid trust verdict generated by Component 1 from the shared
SQLite database (e.g. 'adl.db' or 'trust.db') without stalling the real-time telemetry stream.

A trust verdict includes:
  - device_id: Unique sensor identifier
  - trust_score: Normalized trust score [0.0 - 1.0] (T)
  - trust_level: Tier status ('FULL_TRUST', 'CONDITIONAL', 'BLOCKED', 'REJECTED')
  - monitoring_flag: Active monitoring flag status (int / bool)
  - timestamp: Generation timestamp (ISO-8601 string or Unix epoch)

NFR2 (Component Independence):
  If the database is locked, uninitialized, or missing a record for the device,
  the client safely falls back to 'default_dts_fallback' (0.70).
"""

import os
import sqlite3
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Dict, Any, Optional, Tuple


@dataclass
class TrustVerdict:
    device_id: str
    trust_score: float
    trust_level: str
    monitoring_flag: bool
    timestamp: str
    is_valid: bool = True
    reason: str = "VALID"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "device_id": self.device_id,
            "trust_score": self.trust_score,
            "trust_level": self.trust_level,
            "monitoring_flag": self.monitoring_flag,
            "timestamp": self.timestamp,
            "is_valid": self.is_valid,
            "reason": self.reason,
        }


class TrustVerdictClient:
    """
    Connects to the shared Component 1 SQLite database and retrieves
    the latest valid trust verdict for a given device ID.
    """

    def __init__(
        self,
        db_path: str = "trust.db",
        fallback_dts: float = 0.70,
        cache_ttl_seconds: float = 60.0,
    ):
        self.db_path = db_path
        self.fallback_dts = fallback_dts
        self.cache_ttl = cache_ttl_seconds
        self._cache: Dict[str, Tuple[TrustVerdict, float]] = {}

    def _get_connection(self) -> Optional[sqlite3.Connection]:
        """Opens a connection to the SQLite database (read-only if file exists)."""
        if not os.path.exists(self.db_path):
            return None
        try:
            # Use URI mode=ro when possible for read-only non-blocking access
            abs_path = os.path.abspath(self.db_path).replace("\\", "/")
            conn_uri = f"file:{abs_path}?mode=ro"
            conn = sqlite3.connect(conn_uri, uri=True, timeout=1.0)
            conn.row_factory = sqlite3.Row
            return conn
        except sqlite3.OperationalError:
            # Fallback to standard connect if URI mode fails
            try:
                conn = sqlite3.connect(self.db_path, timeout=1.0)
                conn.row_factory = sqlite3.Row
                return conn
            except Exception:
                return None

    def get_latest_verdict(self, device_id: str) -> TrustVerdict:
        """
        Retrieves the latest valid verdict for device_id from cache or SQLite database.
        Returns a fallback verdict if no record exists or if the database is inaccessible.
        """
        now = time.time()

        # Check local cache first for sub-millisecond retrieval (< 5 ms latency budget)
        if device_id in self._cache:
            verdict, cached_at = self._cache[device_id]
            if (now - cached_at) < self.cache_ttl:
                return verdict

        conn = self._get_connection()
        if conn is None:
            return self._fallback_verdict(device_id, reason="DATABASE_UNAVAILABLE")

        try:
            cursor = conn.cursor()

            # Detect available schema: 'trust_verdicts' or Component 1's 'trust_decisions'
            cursor.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name IN ('trust_verdicts', 'trust_decisions')"
            )
            tables = [row["name"] for row in cursor.fetchall()]

            verdict: Optional[TrustVerdict] = None

            if "trust_verdicts" in tables:
                query = """
                    SELECT device_id, trust_score, trust_level, monitoring_flag, timestamp
                    FROM trust_verdicts
                    WHERE device_id = ?
                    ORDER BY id DESC LIMIT 1
                """
                cursor.execute(query, (device_id,))
                row = cursor.fetchone()
                if row:
                    score = float(row["trust_score"]) if row["trust_score"] is not None else 0.0
                    level = str(row["trust_level"]).upper()
                    flag = bool(row["monitoring_flag"])
                    ts = str(row["timestamp"])

                    # If blocked or rejected, enforce 0.0 trust
                    if level in ("BLOCKED", "REJECTED"):
                        score = 0.0

                    verdict = TrustVerdict(
                        device_id=device_id,
                        trust_score=max(0.0, min(1.0, score)),
                        trust_level=level,
                        monitoring_flag=flag,
                        timestamp=ts,
                        is_valid=True,
                        reason="FROM_TRUST_VERDICTS",
                    )

            elif "trust_decisions" in tables:
                # Component 1 adl.db schema mapping
                query = """
                    SELECT device_id, T, tier, gate, ts
                    FROM trust_decisions
                    WHERE device_id = ?
                    ORDER BY id DESC LIMIT 1
                """
                cursor.execute(query, (device_id,))
                row = cursor.fetchone()
                if row:
                    tier = str(row["tier"]).upper()
                    raw_t = row["T"]
                    gate = row["gate"]
                    ts = str(row["ts"])

                    # If rejected/blocked or gate failed, device is untrusted
                    if tier in ("BLOCKED", "REJECTED") or gate is not None or raw_t is None:
                        score = 0.0
                    else:
                        score = max(0.0, min(1.0, float(raw_t)))

                    verdict = TrustVerdict(
                        device_id=device_id,
                        trust_score=score,
                        trust_level=tier,
                        monitoring_flag=(tier == "CONDITIONAL"),
                        timestamp=ts,
                        is_valid=True,
                        reason="FROM_TRUST_DECISIONS",
                    )

            conn.close()

            if verdict is not None:
                self._cache[device_id] = (verdict, now)
                return verdict
            else:
                return self._fallback_verdict(device_id, reason="NO_VERDICT_FOUND")

        except Exception as e:
            try:
                conn.close()
            except Exception:
                pass
            return self._fallback_verdict(device_id, reason=f"QUERY_ERROR: {str(e)}")

    def get_trust_score(self, device_id: str) -> float:
        """Convenience method: returns the normalized trust score [0.0 - 1.0] for SPS calculation."""
        verdict = self.get_latest_verdict(device_id)
        return verdict.trust_score

    def _fallback_verdict(self, device_id: str, reason: str) -> TrustVerdict:
        """Constructs a graceful default verdict when database is empty or inaccessible."""
        return TrustVerdict(
            device_id=device_id,
            trust_score=self.fallback_dts,
            trust_level="FALLBACK",
            monitoring_flag=True,
            timestamp=datetime.now(timezone.utc).isoformat(timespec="seconds"),
            is_valid=False,
            reason=reason,
        )


def initialize_trust_verdicts_table(db_path: str = "trust.db") -> None:
    """Helper function to create the trust_verdicts table in a shared SQLite database."""
    conn = sqlite3.connect(db_path)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS trust_verdicts (
            id               INTEGER PRIMARY KEY AUTOINCREMENT,
            device_id        TEXT NOT NULL,
            trust_score      REAL NOT NULL,
            trust_level      TEXT NOT NULL,
            monitoring_flag  INTEGER DEFAULT 0,
            timestamp        TEXT NOT NULL
        );
    """)
    conn.commit()
    conn.close()


def insert_trust_verdict(
    db_path: str,
    device_id: str,
    trust_score: float,
    trust_level: str,
    monitoring_flag: bool = False,
    timestamp: Optional[str] = None,
) -> None:
    """Helper function simulating Component 1 writing a verdict into the shared database."""
    initialize_trust_verdicts_table(db_path)
    ts = timestamp or datetime.now(timezone.utc).isoformat(timespec="seconds")
    conn = sqlite3.connect(db_path)
    conn.execute(
        "INSERT INTO trust_verdicts (device_id, trust_score, trust_level, monitoring_flag, timestamp) "
        "VALUES (?, ?, ?, ?, ?)",
        (device_id, float(trust_score), trust_level.upper(), 1 if monitoring_flag else 0, ts),
    )
    conn.commit()
    conn.close()


